CREATE OR REPLACE FUNCTION document_search_vector_update() RETURNS trigger AS $$
BEGIN
  NEW.search_vector :=
    setweight(to_tsvector('english', coalesce(NEW.title, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(NEW.description, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(NEW.filename, '')), 'C');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER document_search_vector_trigger
  BEFORE INSERT OR UPDATE OF title, description, filename ON "Document"
  FOR EACH ROW EXECUTE FUNCTION document_search_vector_update();

CREATE INDEX document_search_vector_idx ON "Document" USING GIN (search_vector);

